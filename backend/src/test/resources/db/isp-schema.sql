-- ISP tables used by repository tests, run on H2 in Oracle mode. Column definitions match the ISP
-- Oracle schema; CLIENT_LOCATION stands in for the Forest Client synonym.

CREATE TABLE ISP_SELL_PRICE_ZONE_CODE
 (ISP_SELL_PRICE_ZONE_CODE VARCHAR2(2) NOT NULL PRIMARY KEY
 ,DESCRIPTION VARCHAR2(120) NOT NULL
 ,EFFECTIVE_DATE DATE NOT NULL
 ,EXPIRY_DATE DATE NOT NULL
 ,UPDATE_TIMESTAMP DATE NOT NULL
 );

CREATE TABLE CLIENT_LOCATION
 (CLIENT_NUMBER VARCHAR2(8) NOT NULL
 ,CLIENT_LOCN_CODE VARCHAR2(2) NOT NULL
 ,PRIMARY KEY (CLIENT_NUMBER, CLIENT_LOCN_CODE)
 );

CREATE TABLE MILL
 (MILL_ID NUMBER(10,0) NOT NULL PRIMARY KEY
 ,MILL_NUMBER NUMBER(10,0) NOT NULL UNIQUE
 ,MILL_NAME VARCHAR2(100) NOT NULL
 ,ISP_SELL_PRICE_ZONE_CODE VARCHAR2(2) REFERENCES ISP_SELL_PRICE_ZONE_CODE
 ,CLIENT_NUMBER VARCHAR2(8) NOT NULL
 ,CLIENT_LOCN_CODE VARCHAR2(2) NOT NULL
 ,EFFECTIVE_DATE DATE NOT NULL
 ,EXPIRY_DATE DATE DEFAULT TO_DATE('9999-12-31','YYYY-MM-DD') NOT NULL
 ,COMMENTS VARCHAR2(4000)
 ,REVISION_COUNT NUMBER(5,0) NOT NULL
 ,ENTRY_USERID VARCHAR2(30) NOT NULL
 ,ENTRY_TIMESTAMP DATE NOT NULL
 ,UPDATE_USERID VARCHAR2(30) NOT NULL
 ,UPDATE_TIMESTAMP DATE NOT NULL
 );

CREATE SEQUENCE MILL_SEQ START WITH 100;

-- Stands in for MILL_REPORT, whose foreign key stops a mill with reports being deleted.
CREATE TABLE MILL_REPORT
 (MILL_REPORT_ID NUMBER(10,0) NOT NULL PRIMARY KEY
 ,MILL_ID NUMBER(10,0) NOT NULL REFERENCES MILL
 );
